/**
 * Экранирует спецсимволы HTML/XML для предотвращения XSS и корректного рендеринга.
 * @param {string} str - Входная строка.
 * @returns {string} Экранированная строка.
 */
function escapeHtml(str) {
    if (!str) return '';
    return String(str).replace(/[&<>"']/g, m => ({
        '&': '&amp;',
        '<': '&lt;',
        '>': '&gt;',
        '"': '&quot;',
        "'": '&#039;'
    })[m]);
}


